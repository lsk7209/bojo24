async function main() {
  const tursoUrl = process.env.TURSO_DATABASE_URL;
  const tursoToken = process.env.TURSO_AUTH_TOKEN;
  if (!tursoUrl || !tursoToken) throw new Error("TURSO env 필요");
  const { createClient } = await import("@libsql/client");
  const db = createClient({ url: tursoUrl, authToken: tursoToken });
  const baseTimeStr = process.env.SCHEDULE_BASE_TIME;
  const baseTime = baseTimeStr ? new Date(baseTimeStr) : new Date();
  const intervalHours = 5;
  let inserted = 0;
  for (let i = 0; i < articles.length; i++) {
    const a = articles[i];
    const slug = mkSlug(a.title);
    const excerpt = a.content.replace(/[#*`>\-|]/g, "").replace(/\s+/g, " ").slice(0, 140).trim() + "…";
    const tags = JSON.stringify(a.tags);
    const scheduledAt = new Date(baseTime.getTime() + i * intervalHours * 3600 * 1000).toISOString();
    await db.execute({
      sql: `INSERT OR IGNORE INTO posts (slug, title, content, excerpt, tags, is_published, published_at) VALUES (?, ?, ?, ?, ?, 1, ?)`,
      args: [slug, a.title, a.content, excerpt, tags, scheduledAt],
    });
    inserted++;
    console.log(`[${inserted}/${articles.length}] ${a.title} → ${scheduledAt}`);
  }
  console.log(`완료: ${inserted}개 삽입`);
}
main().catch(e => { console.error(e); process.exit(1); });
